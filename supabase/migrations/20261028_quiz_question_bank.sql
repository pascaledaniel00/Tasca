-- Archivio privato delle domande quiz pre-generate da Cloudflare Workers AI.
-- Eseguire nel Supabase SQL Editor prima di attivare il cron.
create table if not exists public.quiz_question_bank (
  id bigint generated by default as identity primary key,
  week_start date not null,
  category text not null check (category in ('budget','saving','debt','spending','banking','economy')),
  question jsonb not null,
  fingerprint text not null,
  created_at timestamptz not null default now(),
  constraint quiz_question_bank_week_fingerprint unique (week_start, fingerprint)
);
create index if not exists quiz_question_bank_week_category_idx
  on public.quiz_question_bank (week_start, category);
alter table public.quiz_question_bank enable row level security;
revoke all on public.quiz_question_bank from anon, authenticated;
grant select, insert, update, delete on public.quiz_question_bank to service_role;
