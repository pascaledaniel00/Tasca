-- Tasca: storico permanente delle domande affrontate per account.
-- Eseguire nel Supabase SQL Editor prima di distribuire Worker e interfaccia aggiornati.
create table if not exists public.quiz_question_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  question_fingerprint text not null check (length(question_fingerprint) between 1 and 240),
  category text not null check (category in ('budget','saving','debt','spending','banking','economy')),
  difficulty smallint not null check (difficulty between 1 and 3),
  selected_value text not null,
  is_correct boolean not null,
  answered_at timestamptz not null default now(),
  constraint quiz_question_history_user_question_unique unique (user_id, question_fingerprint)
);

create index if not exists quiz_question_history_user_answered_idx
  on public.quiz_question_history (user_id, answered_at desc);

alter table public.quiz_question_history enable row level security;
drop policy if exists "Users can read their own quiz question history" on public.quiz_question_history;
create policy "Users can read their own quiz question history"
  on public.quiz_question_history for select to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Users can record their own quiz answers" on public.quiz_question_history;
create policy "Users can record their own quiz answers"
  on public.quiz_question_history for insert to authenticated
  with check (auth.uid() = user_id);

revoke all on public.quiz_question_history from anon;
grant select, insert on public.quiz_question_history to authenticated;
grant select, insert, update, delete on public.quiz_question_history to service_role;

-- Le partite da 12 domande richiedono limiti più alti nello storico dei risultati.
alter table public.quiz_attempts
  drop constraint if exists quiz_attempts_total_questions_check;
alter table public.quiz_attempts
  add constraint quiz_attempts_total_questions_check check (total_questions between 1 and 12);

alter table public.quiz_attempts
  drop constraint if exists quiz_attempts_xp_earned_check;
alter table public.quiz_attempts
  add constraint quiz_attempts_xp_earned_check check (xp_earned between 0 and 150);
